-- =====================================================
-- 知识库管理菜单父级归属修复 Migration
-- 日期: 2026-07-18
-- 背景: sys_menus 中「知识库管理」(id=8) 的 parent_id=0，
--       导致它成为孤立顶级菜单，无法归入「系统配置」(id=7) 目录，
--       且在角色管理权限树中显示为顶级项而非系统配置子项。
-- 修复: id=8 parent_id -> 7
-- 说明: 权限码 menu:rag -> menu:knowledge 的拆分由
--       V20260718_01__fix_document_center_route.sql 负责，本迁移只修父级归属。
-- 全部语句幂等可重复执行。
-- =====================================================

UPDATE `sys_menus`
   SET `parent_id` = 7
 WHERE `id` = 8
   AND `parent_id` <> 7;

